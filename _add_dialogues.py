for fpath in sorted(DIR.glob("*.json")):
    name = fpath.stem
    with open(fpath, "r", encoding="utf-8") as f:
        data = json.load(f)
    char_name = data.get("name", "")
    # 找匹配的补充台词
    for key, lines in extra.items():
        if key in char_name or char_name in key or char_name == name:
            existing = set(data.get("source_dialogues", []))
            added = 0
            for l in lines:
                if l not in existing:
                    data.setdefault("source_dialogues", []).append(l)
                    added += 1
            if added:
                total = len(data["source_dialogues"])
                print(f"  {char_name}: +{added} 条，共 {total} 条")
            break
    with open(fpath, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

print("\n完成")
