import json, os

def save(name, lines):
    path = f'd:/aibot/characters/{name}.json'
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    data['source_dialogues'] = lines
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f'{data["name"]}: {len(lines)} 条')

